-- Table for editor constellation access (user_id = users.id, constellation_id = constellations.id). Admins see all; editors see only rows here.
CREATE TABLE IF NOT EXISTS user_constellations (
    user_id VARCHAR(255) NOT NULL,
    constellation_id INT NOT NULL,
    access_level VARCHAR(16) NOT NULL DEFAULT 'read_write' CHECK (access_level IN ('read_write','read_only')), -- read_only = editor may list/open but not mutate this galaxy's components
    PRIMARY KEY (user_id, constellation_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (constellation_id) REFERENCES constellations(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_uc_user_id ON user_constellations (user_id);
CREATE INDEX IF NOT EXISTS idx_uc_constellation_id ON user_constellations (constellation_id);

-- Single-use, emailed-link login tokens (editor self-enrollment). One table for
-- several purposes (magic_login, enroll_confirm, vetting); 64-hex token stored
-- SHA-256-hashed; expires_at computed in PHP (UTC). Created lazily by
-- db_ensure_login_tokens_table(); mirrored here for fresh installs.
CREATE TABLE IF NOT EXISTS login_tokens (
    token_hash CHAR(64) NOT NULL PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL,
    purpose VARCHAR(24) NOT NULL,          -- 'magic_login' | 'enroll_confirm' | 'vetting'
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_login_tokens_user_purpose ON login_tokens (user_id, purpose);
CREATE INDEX IF NOT EXISTS idx_login_tokens_expires_at ON login_tokens (expires_at);

-- Table for API keys
CREATE TABLE IF NOT EXISTS api_keys (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_key VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP NULL DEFAULT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX IF NOT EXISTS unique_api_key ON api_keys (api_key);
CREATE INDEX IF NOT EXISTS idx_is_active ON api_keys (is_active);

-- Table for local snapshots (full system backups stored on disk).
-- Excluded from backup dumps (instance-local state).
CREATE TABLE IF NOT EXISTS snapshots (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    size_bytes BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(255) NULL,
    trigger_type VARCHAR(16) NOT NULL DEFAULT 'manual' CHECK (trigger_type IN ('manual','scheduled')),
    note VARCHAR(500) NULL,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS unique_filename ON snapshots (filename);
CREATE INDEX IF NOT EXISTS idx_snapshots_created_at ON snapshots (created_at);
CREATE INDEX IF NOT EXISTS idx_snapshots_created_by ON snapshots (created_by);

-- Schedule for automatic snapshots (single row, id=1).
-- Excluded from backup dumps (instance-local state).
CREATE TABLE IF NOT EXISTS snapshot_schedule (
    id SMALLINT NOT NULL PRIMARY KEY DEFAULT 1,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    hour SMALLINT NOT NULL DEFAULT 3,
    keep_days INT NOT NULL DEFAULT 7,
    last_run_at TIMESTAMP NULL DEFAULT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
